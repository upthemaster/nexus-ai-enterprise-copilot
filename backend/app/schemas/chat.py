"""
Schemas for grounded generation, cross-encoder reranking, and chat responses.

Why: Defining strict Pydantic models for chat queries, source citations, and response payloads
guarantees that generation outputs conform to Section 6.6 of the Master Blueprint,
providing verifiable citation metadata and explicit evidence sufficiency signals.
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field

from app.schemas.citation import SourcePanelItem


class Citation(BaseModel):
    """
    Verifiable citation pointer mapping directly to an ingested document chunk.
    
    Why: Required by Section 6.6 and 18 of the Blueprint. Prevents fabricated sources
    by requiring server-side validation against retrieved chunk IDs.
    """
    citation_index: int = Field(default=1, description="1-based numerical index corresponding to UI citation badges")
    document_id: str = Field(description="Unique identifier of the source document")
    filename: str = Field(description="Original display filename of the document")
    page_number: int = Field(description="1-based page number where the evidence appears")
    chunk_id: str = Field(description="Exact chunk ID providing the factual evidence")
    snippet: Optional[str] = Field(default=None, description="Brief supporting quote or passage text excerpt")
    relevance_score: Optional[float] = Field(default=None, description="Relevance score from reranker or RRF")
    is_direct_quote: bool = Field(default=False, description="Whether the answer directly quotes verbatim text from this chunk")
    quote_span: Optional[str] = Field(default=None, description="Verbatim quote span excerpted in the answer")


class ChatRequest(BaseModel):
    """
    Incoming payload for grounded Q&A.
    """
    query: str = Field(min_length=1, max_length=2000, description="Natural language question or search prompt")
    top_k: int = Field(default=3, ge=1, le=10, description="Number of top reranked passages to supply as context to the LLM")
    document_id: Optional[str] = Field(default=None, description="Optional document ID to restrict retrieval scope")
    candidate_multiplier: int = Field(default=4, ge=1, le=10, description="Multiplier for initial hybrid candidate pool before reranking")
    use_reranker: bool = Field(default=True, description="Whether to apply Cross-Encoder second-stage reranking")
    conversation_id: Optional[str] = Field(default=None, description="Optional conversation UUID to continue a multi-turn session")


class RerankedPassage(BaseModel):
    """
    Passage scored and sorted by the cross-encoder model.
    """
    chunk_id: str = Field(description="Chunk identifier")
    document_id: str = Field(description="Source document identifier")
    filename: str = Field(description="Source document filename")
    page_number: int = Field(description="1-based page number")
    chunk_index: int = Field(description="Sequential chunk position")
    text: str = Field(description="Passage content")
    rerank_score: float = Field(default=0.0, description="Cross-encoder relevance logit score")
    original_hybrid_rank: int = Field(default=1, description="Initial rank position from RRF hybrid retrieval")
    rrf_score: float = Field(default=0.0, description="First-stage Reciprocal Rank Fusion score")


class ChatResponse(BaseModel):
    """
    Grounded answer response adhering to Master Blueprint Section 6.6.
    """
    answer: str = Field(description="Natural language answer grounded strictly in supplied evidence")
    citations: List[Citation] = Field(default_factory=list, description="Verified source citations resolving to retrieved chunks")
    source_panel: List[SourcePanelItem] = Field(default_factory=list, description="Detailed source panel items for UI inspection")
    insufficient_evidence: bool = Field(description="True if available documents lacked sufficient evidence to answer")
    conversation_id: Optional[str] = Field(default=None, description="Conversation session UUID if conversation context is active")
    retrieval_metadata: Dict[str, Any] = Field(default_factory=dict, description="Execution timings, candidate counts, and provider metadata")


class LLMGenerationResult(BaseModel):
    """
    Internal raw result from LLM provider adapter before citation resolution.
    """
    text: str = Field(description="Raw text generated by the model")
    cited_chunk_ids: List[str] = Field(default_factory=list, description="Chunk IDs referenced in the generation")
    insufficient_evidence: bool = Field(default=False, description="Whether model indicated lack of evidence")
    model_name: str = Field(description="Model identifier used for generation")
